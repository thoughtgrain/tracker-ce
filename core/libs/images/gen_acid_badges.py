#!/usr/bin/env python3
"""Generate the ACID synth badges (L2 bitmaps) for the Tracker's synth model list and patch editor.

    python3 core/libs/images/gen_acid_badges.py            # writes the two headers next to this script
    python3 core/libs/images/gen_acid_badges.py --png DIR  # also writes 8x previews for checking by eye

Same method as gen_toro_badges.py, whose pill and packing helpers it reuses: the pill silhouette comes from
the stock CHIP badges, so ACID sits in the model list exactly like the others, and the lettering is drawn
at 8x with plain shapes, box-filtered down and quantized to the four L2 levels. Same cap height and stroke
weight as TORO, so the two open engines read as a pair.

Copyright (c) 2026 briannhinton. MIT.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw

import gen_toro_badges as toro

HERE = os.path.dirname(os.path.abspath(__file__))
SS = toro.SS


def draw_acid(w, h, box):
    """Black lettering on white at SS x, returned as an 8-bit image of size w x h. box = cap-height box."""
    img = Image.new('L', (w * SS, h * SS), 255)
    d = ImageDraw.Draw(img)
    x0, y0, x1, y1 = (v * SS for v in box)
    cap = y1 - y0
    stroke = cap * 0.27
    gap = cap * 0.16
    widths = [cap * 0.98, cap * 0.86, stroke, cap * 0.90]  # A C I D
    total = sum(widths) + gap * 3
    x = x0 + ((x1 - x0) - total) / 2
    ink = 0

    # A: two legs meeting in a flat apex, and a crossbar a little below the middle.
    aw = widths[0]
    apex = stroke * 0.9
    cx = x + aw / 2
    d.polygon([(x, y1), (x + stroke * 1.05, y1), (cx + apex / 2, y0), (cx - apex / 2, y0)], fill=ink)
    d.polygon([(x + aw, y1), (x + aw - stroke * 1.05, y1), (cx - apex / 2, y0), (cx + apex / 2, y0)], fill=ink)
    bar_y = y0 + cap * 0.58
    d.rectangle([x + aw * 0.22, bar_y, x + aw * 0.78, bar_y + stroke * 0.8], fill=ink)
    x += aw + gap

    # C: a ring opened on the right.
    cw = widths[1]
    d.ellipse([x, y0, x + cw * 1.08, y1], fill=ink)
    d.ellipse([x + stroke, y0 + stroke, x + cw * 1.08 - stroke, y1 - stroke], fill=255)
    d.rectangle([x + cw * 0.62, y0 + cap * 0.30, x + cw * 1.2, y1 - cap * 0.30], fill=255)
    x += cw + gap

    # I
    d.rectangle([x, y0, x + stroke, y1], fill=ink)
    x += widths[2] + gap

    # D: stem and a half-round bowl.
    dw = widths[3]
    d.rounded_rectangle([x, y0, x + dw, y1], radius=cap / 2, fill=ink)
    d.rectangle([x, y0, x + dw * 0.4, y1], fill=ink)
    d.rounded_rectangle([x + stroke, y0 + stroke, x + dw - stroke, y1 - stroke],
                        radius=max(1, (cap - 2 * stroke) / 2), fill=255)
    d.rectangle([x + stroke, y0 + stroke, x + dw * 0.4, y1 - stroke], fill=255)

    return img.resize((w, h), Image.BOX)


def compose(template, w, h, stride, box):
    outside, keep = toro.pill_from(toro.read_l2(template, w, h, stride))
    text = draw_acid(w, h, box)
    out = []
    for y in range(h):
        row = []
        for x in range(w):
            if outside[y][x]:
                v = 0
            elif (x, y) in keep:
                v = keep[(x, y)]
            else:
                v = min(3, max(0, int(round(text.getpixel((x, y)) / 85.0))))
            row.append(v)
        out.append(row)
    return out


def write_header(path, name, px, w, h, stride):
    data = toro.pack(px, stride)
    lines = [f'// Generated by gen_acid_badges.py: ACID badge, L2 bitmap ({w}x{h}, stride {stride}).',
             '// Pill silhouette from the stock CHIP badge; lettering drawn by the script. Do not edit by hand.',
             f'const uint8_t {name}[{len(data)}] = {{']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


BADGES = [
    # template, output, symbol, w, h, stride, cap-height box: the same boxes as TORO's
    ('chip_mini_nomark_80x28_L2.h', 'acid_mini_nomark_80x28_L2.h', 'acid_mini_nomark_80x28_L2', 80, 28, 20,
     (14.5, 7.8, 65.5, 20.2)),
    ('chip_med_108x40_L2.h', 'acid_med_108x40_L2.h', 'acid_med_108x40_L2', 108, 40, 27,
     (20.0, 11.0, 88.0, 28.5)),
]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--png', metavar='DIR', help='also write 8x PNG previews into DIR')
    args = ap.parse_args()
    for template, out, sym, w, h, stride, box in BADGES:
        px = compose(os.path.join(HERE, template), w, h, stride, box)
        write_header(os.path.join(HERE, out), sym, px, w, h, stride)
        if args.png:
            os.makedirs(args.png, exist_ok=True)
            toro.preview(px, os.path.join(args.png, out.replace('.h', '.png')))
        print(f'wrote {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
