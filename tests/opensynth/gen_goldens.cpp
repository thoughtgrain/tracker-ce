// Golden generator: renders every scenario in scenarios.h through OpenTracker's own ACD engine
// (OT_ROOT/src/core/audio/engines/acd.cpp, built unmodified) and prints goldens.inc. Run it only to
// refresh the goldens after an intended change, with the OpenTracker commit noted in the PR:
//
//   make -C tests/opensynth goldens OT_ROOT=/path/to/polyend-tracker-re
//
// Parameter defaults and ranges come from CE's table (OpenSynthParams.cpp); test_params in acid_test
// and the PR check them against OpenTracker's kAcd.
#include <cstdio>

#include "audio/engines/acd.h"
#include "audio/synth_engine.h"
#include "open/OpenSynthEngine.h"
#include "open/OpenSynthParams.h"
#include "scenarios.h"

namespace {

struct OtTraits {
    using Params = ot::audio::SynthParams;
    using Voice = ot::audio::SynthVoice;
    using Slot = ot::audio::SynthSlotScratch;
    using Note = ot::audio::SynthNote;
    static constexpr int32_t kEngineId = ot::kSynthEngineAcd;
    static constexpr uint32_t kBlock = ot::audio::kBlock;
    static ot::audio::ISynthEngine* engine() { return ot::audio::synthAcdEngine(); }
};

}  // namespace

int main() {
    int n = 0;
    const opensynth::ParamInfo* t = opensynth::paramTable(opensynth::kOpenEngineAcid, &n);
    float defs[scenarios::kAcidParams], lo[scenarios::kAcidParams], hi[scenarios::kAcidParams];
    for (int i = 0; i < n; ++i) defs[i] = t[i].def, lo[i] = t[i].min, hi[i] = t[i].max;
    std::printf("// Generated by gen_goldens.cpp from OpenTracker's ACD engine. Do not edit.\n");
    for (const auto& sc : scenarios::all())
        std::printf("{\"%s\", 0x%016llxull},\n", sc.name,
                    static_cast<unsigned long long>(scenarios::run<OtTraits>(sc, defs, lo, hi)));
    return 0;
}
